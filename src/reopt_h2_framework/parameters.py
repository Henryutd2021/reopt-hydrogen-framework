def canonical_units() -> Dict[str, str]:
    """``{"<component>.<field>": unit}`` for every parameter (the units ``parameters.csv`` must state)."""
    return {f"{c}.{f}": spec[1] for (c, f), spec in PARAMETERS.items()}


def pwf(years: float, rate: float, escalation: float = 0.0) -> float:
    """Present-worth factor of a uniform annual amount escalating at ``escalation``: Σ_{y=1..N} ((1+e)/(1+d))^y."""
    n = int(round(years))
    if n <= 0:
        return 0.0
    x = (1.0 + escalation) / (1.0 + rate)
    return float(n) if abs(x - 1.0) < 1e-12 else x * (1.0 - x ** n) / (1.0 - x)


@dataclass(frozen=True)
class Parameters:
    """Validated parameter values, ``values[(component, field)]``; only components in use need values."""

    values: Mapping[Tuple[str, str], float]

    def __post_init__(self) -> None:
        for key, v in self.values.items():
            if key not in PARAMETERS:
                raise ValueError(f"unknown parameter {key[0]}.{key[1]}")
            if not isinstance(v, (int, float)) or isinstance(v, bool) or not math.isfinite(v):
                raise ValueError(f"{key[0]}.{key[1]} must be a finite number, got {v!r}")
            lower = PARAMETERS[key][3]
            if v < lower:
                raise ValueError(f"{key[0]}.{key[1]} = {v} is below its lower bound {lower}")
        for comp, fld in (("battery", "initial_soc"), ("battery", "min_soc"), ("tank", "initial_fill"), ("tes", "initial_soc")):
            if self.values.get((comp, fld), 0.0) > 1.0:
                raise ValueError(f"{comp}.{fld} must be in [0, 1]")
        for comp, fld in (("battery", "charge_efficiency"), ("battery", "discharge_efficiency"),
                          ("tes", "charge_efficiency"), ("tes", "discharge_efficiency")):
            if self.values.get((comp, fld), 1.0) > 1.0:
                raise ValueError(f"{comp}.{fld} must be in (0, 1]")
        if self.values.get(("financial", "tax_rate"), 0.0) >= 1.0:
            raise ValueError("financial.tax_rate must be in [0, 1)")
        for comp, fld in (("electrolyzer", "kwh_per_kg"), ("fuel_cell", "kg_per_kwh")):
            if (comp, fld) in self.values and self.values[(comp, fld)] <= 0:
                raise ValueError(f"{comp}.{fld} must be positive")

    @classmethod
    def from_mapping(cls, values: Mapping[str, float]) -> "Parameters":
        """From ``{"component.field": value}``."""
        out = {}
        for name, v in values.items():
            if name.count(".") != 1:
                raise ValueError(f"parameter names are '<component>.<field>', got {name!r}")
            comp, fld = name.split(".")
            out[(comp, fld)] = float(v) if isinstance(v, (int, float)) and not isinstance(v, bool) else v
        return cls(out)

    def get(self, component: str, field: str) -> float:
        """Value, or the default; raises if a required parameter of a component in use is missing."""
        spec = PARAMETERS[(component, field)]
        if (component, field) in self.values:
            return float(self.values[(component, field)])
        if spec[4] is None:
            raise ValueError(f"missing required parameter {component}.{field} ({spec[1]})")
        return float(spec[4])

    def require(self, component: str) -> None:
        """Raise unless every required parameter of ``component`` is given."""
        missing = [f"{c}.{f}" for (c, f), spec in PARAMETERS.items() if c == component and spec[4] is None
                   and (c, f) not in self.values]
        if missing:
            raise ValueError(f"missing required parameters for {component}: {missing}")

    def as_mapping(self) -> Dict[str, float]:
        return {f"{c}.{f}": float(v) for (c, f), v in sorted(self.values.items())}

    def replace(self, **changes: float) -> "Parameters":
        """Copy with ``component__field=value`` changes, e.g. ``replace(electrolyzer__capital_cost=1e4)``."""
        values = dict(self.values)
        for k, v in changes.items():
            comp, _, fld = k.partition("__")
            values[(comp, fld)] = float(v)
        return Parameters(values)

    def scaled(self, factors: Mapping[str, float]) -> "Parameters":
        """Copy with ``{"component.field": factor}`` multipliers (cost sensitivities)."""
        values = dict(self.values)
        for name, factor in factors.items():
            comp, fld = name.split(".")
            values[(comp, fld)] = self.get(comp, fld) * float(factor)
        return Parameters(values)


@dataclass(frozen=True)
class FinancialFactors:
    """Present-worth and tax factors of Eq. (1)."""

    f_om: float      # f^om
    f_e: float       # f^e
    f_tow: float     # f^tow
    discount_rate: float
    years: int

    @classmethod
    def from_parameters(cls, p: Parameters) -> "FinancialFactors":
        p.require("financial")
        n = p.get("financial", "analysis_years")
        d = p.get("financial", "discount_rate")
        return cls(f_om=pwf(n, d, p.get("financial", "om_escalation")),
                   f_e=pwf(n, d, p.get("financial", "energy_escalation")),
                   f_tow=p.get("financial", "tax_rate"), discount_rate=d, years=int(round(n)))

    def f_pi(self, incentive_years: float) -> float:
        """Present-worth factor of a production incentive paid for ``incentive_years`` (no escalation)."""
        return pwf(min(incentive_years, self.years), self.discount_rate, 0.0)


def effective_capital_cost(capex: float, tax_rate: float, discount_rate: float, itc: float = 0.0,
                           macrs: Tuple[float, ...] = ()) -> float:
    """Capital cost net of an investment tax credit and the present value of MACRS depreciation.

    ``capex`` per unit of size; ``itc`` as a share of capex; ``macrs`` the yearly depreciation shares
    (summing to 1). The depreciable basis is reduced by half the ITC. Returns the value to use as c^cm.
    """
    for name, v in (("capex", capex), ("tax_rate", tax_rate), ("discount_rate", discount_rate), ("itc", itc)):
        if not math.isfinite(v) or v < 0:
            raise ValueError(f"{name} must be finite and non-negative")
    if itc > 1 or tax_rate >= 1:
        raise ValueError("itc must be in [0, 1] and tax_rate in [0, 1)")
    if any(not math.isfinite(s) or s < 0 for s in macrs):
        raise ValueError("macrs shares must be finite and non-negative")
    if macrs and abs(sum(macrs) - 1.0) > 1e-6:
        raise ValueError("macrs shares must sum to 1")
    basis = capex * (1.0 - 0.5 * itc)
    shield = tax_rate * sum(basis * s / (1.0 + discount_rate) ** (y + 1) for y, s in enumerate(macrs))
    cost = capex * (1.0 - itc) - shield
    if cost < 0:
        raise ValueError(f"the net capital cost would be negative ({cost:.4g}); the model requires c^cm >= 0")
    return cost
